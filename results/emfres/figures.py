"""``make.py figures``: every paradigm-comparison figure, from frames/ alone.

Each figure is registered once below with the families it draws and the
function that draws it. A figure reads frames/runs.csv (and bands.csv or
timing.csv where it needs them) through emfres.figdata; none reads logs/ or
.personal/. Paths are generated by emfres.naming:

    figures/paradigm-compare/<emf|voip>/<subject>_<window>[_<metric>].png
    figures/paradigm-compare/scoreboard_<windows>.png
    figures/per-band/<dataset>/<comparison>_<window>_mse.png
    figures/series/dots_l336_o96_<metric>.png

Figures are drawn from whatever runs the frames hold: a model whose cluster
sweep is still training shows faded and is left out of every count, and a
re-extraction after the sweep draws it in full with no code change.
"""

from __future__ import annotations

import sys
from pathlib import Path

from . import figdata as FD

# id -> (families it is drawn for, what it answers)
FIGURES = {
    "P1": (("emf",), "model x paradigm dot plot, seed ticks (MAE, MSE)"),
    "P2": (("emf", "voip"), "per-cell gap forest with the tie band, W/T/L and p"),
    "P3": (("emf", "voip"), "per-band log2 ratio heatmap with each band's share of the gap"),
    "P4": (("voip",), "VoIP dot plot, datasets x windows, Persistence as a rule"),
    "P5": (("emf", "voip"), "clustering gain against k, per model"),
    "P6": (("emf", "voip"), "scoreboard of every comparison"),
    "P7": (("emf",), "accuracy against uncontended training cost"),
    "P8": (("emf", "voip"), "coverage and interval width by paradigm"),
    "P9": (("emf", "voip"), "per-seed skill: who collapses"),
    "P10": (("emf",), "the single-series grid, a separate dataset"),
}


def render(frames_dir: Path, outdir: Path, *, families=("emf", "voip"), only=None,
           formats=("png",), style_name: str = "paper", check: bool = True) -> tuple:
    """Draw the selected figures; returns (written paths, spot-check problems)."""
    from . import fig_bands as FB
    from . import fig_cost as FC
    from . import fig_paradigms as FP
    from . import fig_sweep as FS
    from . import figkit as K
    from . import paradigms as PG

    style = K.setup(style_name)
    frames_dir = Path(frames_dir)
    runs_csv = frames_dir / "runs.csv"
    wanted = set(only) if only else set(FIGURES)
    unknown = wanted - set(FIGURES)
    if unknown:
        raise ValueError(f"unknown figure id(s): {', '.join(sorted(unknown))}")
    ranks = K.ranks()
    corpora = {fam: FD.load_family(runs_csv, fam, **ranks) for fam in families}

    problems = []
    if check:
        for fam, cs in corpora.items():
            for corpus in cs:
                n, bad = FD.spot_check(corpus, frames_dir / "cells.csv", runs_csv=runs_csv)
                print(f"spot check {fam} {K.window_label(corpus.window)}: "
                      f"{n - len(bad)}/{n} seed means agree with cells.csv",
                      file=sys.stderr)
                problems += bad
        if "emf" in families:
            n, bad = FD.spot_check_series(runs_csv, frames_dir / "cells.csv")
            print(f"spot check series: {n - len(bad)}/{n} seed means agree with cells.csv",
                  file=sys.stderr)
            problems += bad

    def want(fid, fam):
        return fid in wanted and fam in FIGURES[fid][0] and fam in families

    noted = set()
    for fid, name in (("P3", "bands.csv"), ("P7", "timing.csv")):
        if fid in wanted and not (frames_dir / name).exists():
            print(f"NOTE: {frames_dir / name} not found -- {fid} ({FIGURES[fid][1]}) is not "
                  f"drawn; `make.py extract` writes it", file=sys.stderr)
            noted.add(fid)

    written = []
    drawn: dict = {}

    def draw(fid, fam, paths):
        drawn[(fid, fam)] = drawn.get((fid, fam), 0) + len(paths)
        written.extend(paths)

    for fam, cs in corpora.items():
        if not cs:
            continue
        for metric, _ in PG.METRICS:
            if want("P1", fam):
                draw("P1", fam, FP.fig_dots(cs[:1], metric, style, outdir, formats, family=fam))
            if want("P4", fam):
                draw("P4", fam, FP.fig_dots(cs, metric, style, outdir, formats, family=fam))
            if want("P2", fam):
                for corpus in cs:
                    draw("P2", fam, FP.fig_forest(corpus, metric, style, outdir, formats))
            if want("P5", fam):
                for corpus in cs:
                    draw("P5", fam, FS.fig_k_gain(corpus, metric, style, outdir, formats))
            if want("P7", fam):
                draw("P7", fam, FC.fig_cost(cs[0], runs_csv, frames_dir / "timing.csv", metric,
                                            style, outdir, formats))
        if want("P3", fam):
            for corpus in cs:
                draw("P3", fam, FB.fig_bands(corpus, frames_dir / "bands.csv", style, outdir,
                                             formats))
        if want("P8", fam):
            draw("P8", fam, FC.fig_calibration(cs, runs_csv, style, outdir, formats, family=fam))
        if want("P9", fam):
            draw("P9", fam, FP.fig_seed_skill(cs, style, outdir, formats, family=fam))
    # A figure the frames give nothing to draw (P5 before any cluster run,
    # say) is named, as a missing bands.csv or timing.csv is above.
    for (fid, fam), n in sorted(drawn.items()):
        if not n and fid not in noted:
            print(f"NOTE: nothing in the {fam} frames for {fid} ({FIGURES[fid][1]}) -- "
                  f"it is not drawn", file=sys.stderr)
    if "P6" in wanted:
        written += FP.fig_scoreboard([c for fam in families for c in corpora.get(fam, [])],
                                     style, outdir, formats)
    if "P10" in wanted and "emf" in families:
        for metric, _ in PG.METRICS:
            written += FP.fig_series(runs_csv, metric, style, outdir, formats, **ranks)
    return written, problems
