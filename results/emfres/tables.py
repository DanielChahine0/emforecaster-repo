"""frames/ → tables. Markdown and CSV twins, rendered from the CSVs.

The point of this module is narrow and deliberate: it rebuilds the *existing*
report out of ``frames/runs.csv`` rather than out of a logs/ walk, reusing
extract_results' own renderer. If the result is byte-identical to what the
logs-walking path produces, then the frames layer provably loses nothing --
which is the licence to make the CSVs the source of truth and retire the
markdown-parsing that every plotter still does.

    python results/make.py tables
    python results/make.py tables --check    # rebuild and diff, write nothing
"""

from __future__ import annotations

import csv
import sys
from pathlib import Path
from typing import Optional

# The setup slug on disk -> the section heading the report has always used.
SETUP_TITLES = {
    "multivariate": "Multivariate",
    "series": "Univariate Series",
    "perchannel": "Univariate (Per Channel)",
    "cluster": "Cluster (k-Grouped Channels)",
}

# The order sections appear in the concatenated report.
SETUP_ORDER = ["series", "perchannel", "multivariate", "cluster"]

BANNER = (
    "<!-- Generated by results/make.py tables from frames/runs.csv "
    "({digest}). Do not edit by hand. -->"
)


def _f(v: str) -> Optional[float]:
    return float(v) if v not in ("", None) else None


def _i(v: str) -> Optional[int]:
    return int(v) if v not in ("", None) else None


def runs_from_csv(path: Path, repo: Path, family: Optional[str] = None):
    """Rebuild extract_results.Run objects from frames/runs.csv, keyed by setup.

    ``family`` keeps only one corpus (see frames.family_of). A table mixing the
    EMF and VoIP families would put rows with different channels, windows and
    split fractions in one column and invite exactly the comparison that cannot
    be made, so every renderer takes one family at a time.
    """
    from .frames import family_of
    from .runlogs import Run

    by_setup: dict[str, list] = {}
    with open(path) as f:
        for row in csv.DictReader(f):
            # Re-derived when absent, so a frames file written before the
            # column existed still filters correctly.
            if family is not None and (row.get("family")
                                       or family_of(row["dataset"])) != family:
                continue
            by_setup.setdefault(row["setup"], []).append(Run(
                model=row["model"],
                dataset=row["dataset"],
                seq_len=int(row["seq_len"]),
                pred_len=int(row["pred_len"]),
                conf=bool(int(row["conf"])),
                mse=_f(row["mse"]),
                mae=_f(row["mae"]),
                running_time=_f(row["running_time"]),
                per_epoch=_f(row["per_epoch"]),
                num_params=_i(row["num_params"]),
                ic=_f(row["ic"]),
                jc=_f(row["jc"]),
                interval_width=_f(row["interval_width"]),
                channel=_i(row["channel"]),
                k=_i(row["k"]),
                seed=row["seed"] or None,
                path=repo / row["path"],
                concurrency=_i(row.get("concurrency", "")),
            ))
    return by_setup


def render_sections(runs_csv: Path, repo: Path, results: Path,
                    family: Optional[str] = None) -> list[tuple[str, str, str]]:
    """(setup, title, markdown) for every setup present, in report order."""
    sys.path.insert(0, str(results))
    import extract_results as er

    by_setup = runs_from_csv(runs_csv, repo, family)
    out = []
    for setup in SETUP_ORDER + sorted(set(by_setup) - set(SETUP_ORDER)):
        runs = by_setup.get(setup)
        if not runs:
            continue
        title = SETUP_TITLES.get(setup, setup.title())
        out.append((setup, title, er.render_report(title, runs, er.aggregate(runs))))
    return out


def render_cross_sections(runs_csv: Path, repo: Path, results: Path,
                          family: Optional[str] = None,
                          setting: Optional[tuple] = None) -> list[tuple[str, str, str]]:
    """The three sections that need more than one setup at once.

    ``Multivariate vs Univariate``, ``CCM vs Base`` and ``Ultimate Comparison``
    are joins across setups, so they cannot be rendered from a single tree --
    which is exactly why extract_results only builds them on a full run.
    """
    sys.path.insert(0, str(results))
    import extract_results as er

    # The two cross-setup sections are built for one (L, O). Rebound per corpus
    # and restored, so rendering one family never changes what another renders.
    previous_setting = er.ULTIMATE_SETTING
    if setting is not None:
        er.ULTIMATE_SETTING = setting
    try:
        return _cross_sections(er, runs_csv, repo, family)
    finally:
        er.ULTIMATE_SETTING = previous_setting


def _cross_sections(er, runs_csv: Path, repo: Path, family: Optional[str]):
    by_setup = runs_from_csv(runs_csv, repo, family)
    cells = {SETUP_TITLES[s]: er.aggregate(r)
             for s, r in by_setup.items() if s in SETUP_TITLES}

    out = []
    mv = cells.get(er.MULTIVARIATE_TITLE)
    uv = [(t, c) for t, c in cells.items()
          if t not in (er.MULTIVARIATE_TITLE, er.CLUSTER_TITLE)]
    if mv and uv:
        pc_runs = by_setup.get("perchannel", [])
        md = er.render_comparison(
            er.COMPARISON_TITLE, er.MULTIVARIATE_TITLE, mv, uv,
            concurrency={SETUP_TITLES["perchannel"]: er.concurrency_text(pc_runs)}
            if pc_runs else None)
        if md:
            out.append(("mv-vs-univariate", er.COMPARISON_TITLE, md))

    cl = cells.get(er.CLUSTER_TITLE)
    if mv and cl:
        cluster_runs = by_setup.get("cluster", [])
        md = er.render_ccm_vs_base(er.CCM_TITLE, er.canonical_cells(cl),
                                   er.canonical_cells(mv), cluster_runs)
        if md:
            out.append(("ccm-vs-base", er.CCM_TITLE, md))

    pipelines = er.build_pipelines(cells)
    if pipelines:
        pc_runs = by_setup.get("perchannel", [])
        md = er.render_ultimate(er.ULTIMATE_TITLE, pipelines,
                                er.concurrency_text(pc_runs) if pc_runs else None)
        if md:
            out.append(("pipelines", er.ULTIMATE_TITLE, md))
    return out


def cells_csv_twins(cells_csv: Path, outdir: Path,
                    family: Optional[str] = None) -> list[Path]:
    """One flat CSV per setup, so a table can be opened without a markdown parser."""
    from .frames import family_of

    rows_by_setup: dict[str, list[dict]] = {}
    with open(cells_csv) as f:
        reader = csv.DictReader(f)
        fields = reader.fieldnames or []
        for row in reader:
            if family is not None and (row.get("family")
                                       or family_of(row["dataset"])) != family:
                continue
            rows_by_setup.setdefault(row["setup"], []).append(row)

    outdir.mkdir(parents=True, exist_ok=True)
    written = []
    for setup, rows in sorted(rows_by_setup.items()):
        path = outdir / f"{setup}.csv"
        with open(path, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=fields, lineterminator="\n")
            w.writeheader()
            w.writerows(rows)
        written.append(path)
    return written


